#!/bin/bash

set -euo pipefail

if [[ $# -ne 7 ]]; then
    echo "Usage: $0 <source-json> <version> <version-date> <size> <download-url> <website> <source-url>" >&2
    exit 2
fi

source_path="$1"
version="$2"
version_date="$3"
size="$4"
download_url="$5"
website="$6"
source_url="$7"

if [[ ! -f "$source_path" ]]; then
    echo "SideStore source not found: $source_path" >&2
    exit 1
fi

temporary_path="$(mktemp "${TMPDIR:-/tmp}/devicehub-mask-source.XXXXXX")"
trap 'rm -f "$temporary_path"' EXIT

jq \
    --arg version "$version" \
    --arg version_date "$version_date" \
    --arg download_url "$download_url" \
    --arg website "$website" \
    --arg source_url "$source_url" \
    --argjson size "$size" \
    ' .website = $website
    | .sourceURL = $source_url
    | .apps[0].version = $version
    | .apps[0].versionDate = $version_date
    | .apps[0].downloadURL = $download_url
    | .apps[0].size = $size
    | .apps[0].versionDescription = "Unsigned IPA generated by GitHub Actions. SideStore or AltStore signs it during installation."' \
    "$source_path" > "$temporary_path"

mv "$temporary_path" "$source_path"
